-- =============================================================================
-- CHU Lakehouse : DDL du Gold PostgreSQL (base chu_gold_db)
-- Étoile de Kimball : 6 dimensions, 4 faits.
-- Référence : Livrable 1, modèle logique (§3.7) et dictionnaire de données (annexe A).
--
-- Usage (racine du dépôt, sur la VM) :
--   docker exec -i chu_postgres psql -U chu_admin -d chu_gold_db -v ON_ERROR_STOP=1 < sql/gold_ddl.sql
--
-- Le script est rejouable : il supprime puis recrée les 10 tables.
-- ATTENTION : il efface donc aussi l'historique SCD2 de dim_etablissement.
--
-- Contenu :
--   - tables, clés primaires, clés étrangères, contraintes NOT NULL / UNIQUE / CHECK ;
--   - ligne -1 « Inconnu » dans chaque dimension (règle §6.2 : clé étrangère introuvable -> -1) ;
--   - les 18 régions INSEE + « Étranger » : référentiel figé, nécessaire avant le SCD2
--     de dim_etablissement (J22), qui est tenu dans PostgreSQL.
-- Hors de ce script, pour pouvoir mesurer l'avant/après du benchmark :
--   - index secondaires : sql/gold_index.sql
--   - partitionnement des faits : sql/gold_partition.sql
--
-- Choix faits là où le livrable 1 se contredit (à reporter dans le rapport) :
--   - pas de DIM_DEMOGRAPHIE : sexe et tranche_age restent dans fait_deces (annexe A) ;
--   - pas d'id_region dans les faits, sauf fait_deces : la région passe par l'établissement (§3.6) ;
--   - version courante SCD2 : est_courant (annexe A), et non est_actif (§3.7) ;
--   - commune : VARCHAR(60) au lieu de 30 (le plus long nom de commune fait 45 caractères) ;
--   - colonnes techniques run_id et date_chargement sur chaque table (traçabilité, §6.1 et §7.4).
-- =============================================================================

BEGIN;

DROP TABLE IF EXISTS fait_consultation, fait_hospitalisation, fait_deces, fait_satisfaction CASCADE;
DROP TABLE IF EXISTS dim_etablissement, dim_region, dim_temps,
                     dim_patient, dim_professionnel, dim_diagnostic CASCADE;


-- =============================================================================
-- DIMENSIONS
-- Clés de substitution en INTEGER simple : elles sont calculées par Spark (Hive)
-- et recopiées telles quelles par J34. Seule dim_etablissement, tenue dans
-- PostgreSQL (SCD2), génère ses clés elle-même.
-- =============================================================================

-- ---------------------------------------------------------------- DIM_TEMPS
-- Générée par J20 du 01/01/1970 au 31/12/2030. Dimension à rôles multiples
-- (date d'entrée et date de sortie des hospitalisations).
CREATE TABLE dim_temps (
    id_date          INTEGER      PRIMARY KEY,       -- AAAAMMJJ ; -1 = Inconnu
    date_complete    DATE         NOT NULL UNIQUE,
    jour             SMALLINT     NOT NULL,          -- 1 à 31
    jour_semaine     VARCHAR(10)  NOT NULL,          -- Lundi à Dimanche
    semaine_iso      SMALLINT     NOT NULL,          -- 1 à 53
    mois             SMALLINT     NOT NULL,          -- 1 à 12
    libelle_mois     VARCHAR(10)  NOT NULL,          -- Janvier à Décembre
    trimestre        SMALLINT     NOT NULL,          -- 1 à 4
    annee            SMALLINT     NOT NULL,
    est_ferie        BOOLEAN      NOT NULL,          -- calendrier des jours fériés français
    run_id           VARCHAR(40),
    date_chargement  TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_temps_domaines CHECK (id_date = -1 OR (
        jour BETWEEN 1 AND 31 AND mois BETWEEN 1 AND 12
        AND trimestre BETWEEN 1 AND 4 AND semaine_iso BETWEEN 1 AND 53)),
    -- La clé doit correspondre à la date : 2020-03-15 -> 20200315
    CONSTRAINT ck_temps_cle CHECK (id_date = -1 OR id_date =
        (EXTRACT(YEAR FROM date_complete) * 10000
       + EXTRACT(MONTH FROM date_complete) * 100
       + EXTRACT(DAY FROM date_complete))::INTEGER)
);

-- ---------------------------------------------------------------- DIM_REGION
-- Clé technique = code INSEE converti en entier (stable) ; -1 = Inconnu (code ZZ).
CREATE TABLE dim_region (
    id_region          INTEGER      PRIMARY KEY,
    code_region_insee  CHAR(2)      NOT NULL UNIQUE,  -- « 99 » = Étranger ; « ZZ » = Inconnu
    libelle_region     VARCHAR(60)  NOT NULL,
    run_id             VARCHAR(40),
    date_chargement    TIMESTAMP    NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- DIM_ETABLISSEMENT
-- SCD2 tenu dans PostgreSQL (J22) : une ligne par version d'un établissement.
-- Clé naturelle : identifiant_organisation. Flocon assumé vers dim_region (§3.6).
CREATE TABLE dim_etablissement (
    id_etablissement          INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant_organisation  VARCHAR(30)   NOT NULL,   -- clé métier, jointure avec l'hospitalisation
    finess_site               CHAR(9),                  -- texte, zéros initiaux conservés
    finess_juridique          CHAR(9),
    siret_site                CHAR(14),
    siren_site                CHAR(9),
    raison_sociale            VARCHAR(150)  NOT NULL,
    enseigne                  VARCHAR(150),
    categorie                 VARCHAR(30),
    code_commune              VARCHAR(30),
    commune                   VARCHAR(60),
    code_postal               VARCHAR(30)   NOT NULL,
    code_departement          VARCHAR(30),              -- dérivé du code commune
    id_region                 INTEGER       NOT NULL REFERENCES dim_region (id_region),
    date_debut                DATE          NOT NULL,   -- premier jour de validité de la version
    date_fin                  DATE          NOT NULL DEFAULT DATE '9999-12-31',
    est_courant               BOOLEAN       NOT NULL DEFAULT TRUE,
    run_id                    VARCHAR(40),
    date_chargement           TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT uq_etablissement_version UNIQUE (identifiant_organisation, date_debut),
    CONSTRAINT ck_etablissement_periode CHECK (date_fin >= date_debut),
    CONSTRAINT ck_etablissement_courant CHECK (est_courant = (date_fin = DATE '9999-12-31'))
);
-- Une seule version courante par établissement (règle du SCD2).
CREATE UNIQUE INDEX uq_etablissement_courant
    ON dim_etablissement (identifiant_organisation) WHERE est_courant;

-- ---------------------------------------------------------------- DIM_PATIENT
CREATE TABLE dim_patient (
    id_patient       INTEGER   PRIMARY KEY,
    patient_pseudo   CHAR(64)  NOT NULL UNIQUE,   -- HMAC-SHA256, aucune donnée nominative
    sexe             CHAR(1)   NOT NULL,          -- F, M ou I (autre ou vide)
    annee_naissance  SMALLINT,
    run_id           VARCHAR(40),
    date_chargement  TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_patient_sexe CHECK (sexe IN ('F', 'M', 'I')),
    CONSTRAINT ck_patient_annee CHECK (annee_naissance BETWEEN 1880 AND 2100)
);

-- ---------------------------------------------------------------- DIM_PROFESSIONNEL
CREATE TABLE dim_professionnel (
    id_professionnel           INTEGER      PRIMARY KEY,
    identifiant_pseudo         CHAR(64)     NOT NULL UNIQUE,   -- HMAC-SHA256 ; nom et prénom exclus
    type_identifiant           VARCHAR(10),
    categorie_professionnelle  VARCHAR(30),
    profession                 VARCHAR(60),                    -- « Non renseigné » si vide
    fonction                   VARCHAR(30),
    specialite                 VARCHAR(80),
    run_id                     VARCHAR(40),
    date_chargement            TIMESTAMP    NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- DIM_DIAGNOSTIC
CREATE TABLE dim_diagnostic (
    id_diagnostic       INTEGER       PRIMARY KEY,
    code_diagnostic     VARCHAR(10)   NOT NULL UNIQUE,
    libelle_diagnostic  VARCHAR(255)  NOT NULL,
    run_id              VARCHAR(40),
    date_chargement     TIMESTAMP     NOT NULL DEFAULT now()
);

-- =============================================================================
-- FAITS
-- Toutes les clés étrangères sont NOT NULL (§3.6) : une référence introuvable
-- pointe vers la ligne -1 de la dimension.
-- =============================================================================

-- ---------------------------------------------------------------- FAIT_CONSULTATION
-- Grain : une consultation (environ 1,03 million de lignes).
CREATE TABLE fait_consultation (
    id_consultation   INTEGER   PRIMARY KEY,   -- Num_consultation (clé dégénérée)
    id_date           INTEGER   NOT NULL REFERENCES dim_temps (id_date),
    id_patient        INTEGER   NOT NULL REFERENCES dim_patient (id_patient),
    id_professionnel  INTEGER   NOT NULL REFERENCES dim_professionnel (id_professionnel),
    id_diagnostic     INTEGER   NOT NULL REFERENCES dim_diagnostic (id_diagnostic),
    id_etablissement  INTEGER   NOT NULL REFERENCES dim_etablissement (id_etablissement),
    heure_debut       TIME,
    heure_fin         TIME,
    duree_minutes     SMALLINT,                -- fin - début, + 1440 au passage de minuit
    nb_consultations  SMALLINT  NOT NULL DEFAULT 1,
    run_id            VARCHAR(40),
    date_chargement   TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT ck_consultation_duree CHECK (duree_minutes BETWEEN 0 AND 1440),
    CONSTRAINT ck_consultation_nb CHECK (nb_consultations = 1)
);

-- ---------------------------------------------------------------- FAIT_HOSPITALISATION
-- Grain : un séjour. dim_temps joue deux rôles (entrée et sortie).
CREATE TABLE fait_hospitalisation (
    id_hospitalisation   VARCHAR(20)  PRIMARY KEY,   -- Num_Hospitalisation (clé dégénérée)
    id_date_entree       INTEGER      NOT NULL REFERENCES dim_temps (id_date),
    id_date_sortie       INTEGER      NOT NULL REFERENCES dim_temps (id_date),  -- -1 si durée inconnue
    id_patient           INTEGER      NOT NULL REFERENCES dim_patient (id_patient),
    id_etablissement     INTEGER      NOT NULL REFERENCES dim_etablissement (id_etablissement),
    id_diagnostic        INTEGER      NOT NULL REFERENCES dim_diagnostic (id_diagnostic),
    duree_sejour_jours   SMALLINT,
    nb_hospitalisations  SMALLINT     NOT NULL DEFAULT 1,
    run_id               VARCHAR(40),
    date_chargement      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_hospitalisation_duree CHECK (duree_sejour_jours >= 0),
    CONSTRAINT ck_hospitalisation_nb CHECK (nb_hospitalisations = 1),
    -- Les clés AAAAMMJJ se comparent dans l'ordre chronologique.
    CONSTRAINT ck_hospitalisation_dates CHECK (id_date_sortie = -1 OR id_date_sortie >= id_date_entree)
);

-- ---------------------------------------------------------------- FAIT_DECES
-- Grain : un décès du fichier INSEE. Jamais relié aux patients du CHU (RGPD).
CREATE TABLE fait_deces (
    id_deces         INTEGER     PRIMARY KEY,
    id_date          INTEGER     NOT NULL REFERENCES dim_temps (id_date),
    id_region        INTEGER     NOT NULL REFERENCES dim_region (id_region),  -- région du lieu de décès
    sexe             CHAR(1)     NOT NULL,
    tranche_age      VARCHAR(7),                                             -- 0-4, 5-9, ..., 95+
    nb_deces         SMALLINT    NOT NULL DEFAULT 1,
    run_id           VARCHAR(40),
    date_chargement  TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT ck_deces_sexe CHECK (sexe IN ('F', 'M', 'I')),
    CONSTRAINT ck_deces_nb CHECK (nb_deces = 1)
);

-- ---------------------------------------------------------------- FAIT_SATISFACTION
-- Grain : un établissement x une année x un type d'enquête.
-- Scores non additifs : moyenne pondérée par nb_reponses, calculée dans Superset.
CREATE TABLE fait_satisfaction (
    id_satisfaction      INTEGER       PRIMARY KEY,
    id_date              INTEGER       NOT NULL REFERENCES dim_temps (id_date),  -- 1er janvier de l'année de campagne
    id_etablissement     INTEGER       NOT NULL REFERENCES dim_etablissement (id_etablissement),
    type_enquete         VARCHAR(3)    NOT NULL,   -- 48H ou CA
    classement           VARCHAR(2),
    evolution            VARCHAR(30),
    nb_reponses          INTEGER,
    score_global         DECIMAL(5,2),
    score_accueil        DECIMAL(5,2),
    score_pec_infirmier  DECIMAL(5,2),             -- enquête 48H seulement
    score_pec_medical    DECIMAL(5,2),             -- enquête 48H seulement
    score_chambre        DECIMAL(5,2),
    score_repas          DECIMAL(5,2),             -- enquête 48H seulement
    score_sortie         DECIMAL(5,2),
    taux_recommandation  DECIMAL(5,2),             -- NULL en 2017
    run_id               VARCHAR(40),
    date_chargement      TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_satisfaction_type CHECK (type_enquete IN ('48H', 'CA')),
    CONSTRAINT ck_satisfaction_classement CHECK (classement IN ('A', 'B', 'C', 'D', 'DI', 'NV', 'NR')),
    CONSTRAINT ck_satisfaction_reponses CHECK (nb_reponses >= 0),
    CONSTRAINT ck_satisfaction_scores CHECK (
            score_global        BETWEEN 0 AND 100
        AND score_accueil       BETWEEN 0 AND 100
        AND score_pec_infirmier BETWEEN 0 AND 100
        AND score_pec_medical   BETWEEN 0 AND 100
        AND score_chambre       BETWEEN 0 AND 100
        AND score_repas         BETWEEN 0 AND 100
        AND score_sortie        BETWEEN 0 AND 100
        AND taux_recommandation BETWEEN 0 AND 100)
);
-- Une mesure par établissement, année et type d'enquête. Index partiel : plusieurs
-- établissements non résolus (-1) peuvent exister pour la même année et la même enquête.
CREATE UNIQUE INDEX uq_satisfaction_mesure
    ON fait_satisfaction (id_date, id_etablissement, type_enquete)
    WHERE id_etablissement <> -1;


